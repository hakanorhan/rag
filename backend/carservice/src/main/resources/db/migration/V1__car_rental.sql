CREATE TABLE car_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500),
    daily_rate NUMERIC(10, 2) NOT NULL CHECK (daily_rate >= 0),

    minimum_age INTEGER NOT NULL
        CHECK (minimum_age IN (18, 21, 25))
);

CREATE TABLE location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    city VARCHAR(100) NOT NULL,
    country VARCHAR(100) NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keycloak_id VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30),
    driver_license_number VARCHAR(100) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_category VARCHAR(100) NOT NULL,

    car_type_id BIGINT NOT NULL REFERENCES car_type(id),
    location_id BIGINT NOT NULL REFERENCES location(id),

    image_url VARCHAR(1000),

    license_plate VARCHAR(20) NOT NULL UNIQUE,

    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (
            status IN (
                'AVAILABLE',
                'RENTED',
                'MAINTENANCE'
            )
        )
);

CREATE TABLE extra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500),
    price_per_day NUMERIC(10, 2) NOT NULL
        CHECK (price_per_day >= 0)
);

CREATE TABLE reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL REFERENCES users(id),
    car_id BIGINT NOT NULL REFERENCES cars(id),

    pickup_location_id BIGINT NOT NULL REFERENCES location(id),
    return_location_id BIGINT NOT NULL REFERENCES location(id),

    pickup_at TIMESTAMPTZ NOT NULL,
    return_at TIMESTAMPTZ NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'RESERVED'
        CHECK (
            status IN (
                'RESERVED',
                'ACTIVE',
                'COMPLETED',
                'CANCELLED'
            )
        ),

    daily_rate NUMERIC(10, 2) NOT NULL
        CHECK (daily_rate >= 0),

    total_price NUMERIC(10, 2) NOT NULL
        CHECK (total_price >= 0),

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CHECK (return_at > pickup_at)
);

CREATE TABLE reservation_extra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reservation_id BIGINT NOT NULL
        REFERENCES reservation(id) ON DELETE CASCADE,

    extra_id BIGINT NOT NULL
        REFERENCES extra(id),

    quantity INTEGER NOT NULL DEFAULT 1
        CHECK (quantity > 0),

    unit_price NUMERIC(10, 2) NOT NULL
        CHECK (unit_price >= 0),

    UNIQUE (reservation_id, extra_id)
);


-- Indizes für Foreign Keys

CREATE INDEX idx_cars_car_type_id
    ON cars(car_type_id);

CREATE INDEX idx_cars_location_id
    ON cars(location_id);

CREATE INDEX idx_reservation_user_id
    ON reservation(user_id);

CREATE INDEX idx_reservation_car_id
    ON reservation(car_id);

CREATE INDEX idx_reservation_pickup_location_id
    ON reservation(pickup_location_id);

CREATE INDEX idx_reservation_return_location_id
    ON reservation(return_location_id);

CREATE INDEX idx_reservation_extra_extra_id
    ON reservation_extra(extra_id);
